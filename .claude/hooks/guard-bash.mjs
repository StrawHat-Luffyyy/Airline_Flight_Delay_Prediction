// PreToolUse (Bash): block destructive commands, off-plan dependencies, and unsafe commits.
import { block, projectRoot, readInput, run } from './lib.mjs';

const input = readInput();
const cmd = String(input.tool_input?.command ?? '');
const root = projectRoot(input);

const rules = [
  {
    re: /\bdocker\s+compose\b[^\n;&|]*\bdown\b[^\n;&|]*(\s-v\b|--volumes)/,
    msg: 'Blocked: `docker compose down -v` deletes the MongoDB volume (the 5.8M-row dataset). Use `docker compose down` without -v, or ask the user first.',
  },
  {
    re: /\bdocker\s+volume\s+(rm|prune)\b/,
    msg: 'Blocked: removing Docker volumes can destroy the loaded MongoDB data. Ask the user first.',
  },
  {
    re: /mongosh[\s\S]*(dropDatabase\s*\(|\.drop\s*\()/,
    msg: 'Blocked: dropping a database/collection by hand. Use `npm run ingest -- --drop` (it records an ingest_runs entry) or ask the user.',
  },
  {
    re: /\bgit\s+push\b[^\n;&|]*(--force\b|--force-with-lease|\s-f\b)/,
    msg: 'Blocked: force push. Ask the user.',
  },
  {
    re: /\bgit\s+reset\s+--hard\b/,
    msg: 'Blocked: `git reset --hard` discards work. Ask the user, or use `git stash`.',
  },
  {
    re: /\bgit\s+clean\b[^\n;&|]*\s-[a-zA-Z]*x/,
    msg: 'Blocked: `git clean -x` removes ignored files such as data/ and .env.',
  },
  {
    re: /\brm\b[^\n;&|]*\s(\.\/)?(data\/?|data\/raw\S*|\.git\/?)(\s|$)/,
    msg: 'Blocked: deleting data/ or data/raw or .git. The raw CSVs are not in git and cannot be regenerated by you.',
  },
  {
    re: /\b(npm|yarn|pnpm|bun)\s+(i|install|add)\b[^\n;&|]*\bmongoose\b/,
    msg: 'Blocked: this project uses the official `mongodb` driver, not Mongoose (see PROJECT_OVERVIEW.md section 2).',
  },
  {
    re: /\b(cat|type|less|more|head|tail|bat|Get-Content)\s+[^\n;&|]*\.env(?![.\w])/,
    msg: 'Blocked: do not print .env. Read .env.example for variable names.',
  },
  {
    re: /\b(cat|type|Get-Content|less|more)\s+[^\n;&|]*flights\.csv/,
    msg: 'Blocked: flights.csv is ~592 MB. Use `head -n 5 data/raw/flights.csv` or a streaming script.',
  },
];

for (const { re, msg } of rules) {
  if (re.test(cmd)) block(msg);
}

// ---- commit guard: no data, env files or secrets in commits ----
if (/\bgit\s+commit\b/.test(cmd)) {
  const commitAll = /\bgit\s+commit\b[^\n;&|]*\s-[a-zA-Z]*a/.test(cmd);
  const g = (args) => run('git', args, { cwd: root, timeout: 20000 }).stdout ?? '';

  const names = [
    ...g(['diff', '--cached', '--name-only']).split('\n'),
    ...(commitAll ? g(['diff', '--name-only']).split('\n') : []),
  ].filter(Boolean);

  const badPaths = [
    /^data\//,
    /(^|\/)\.env$/,
    /(^|\/)node_modules\//,
    /(^|\/)dist\//,
    /(^|\/)\.venv\//,
    /\.(csv|zip|parquet)$/i,
  ];
  const badFile = names.find((n) => badPaths.some((re) => re.test(n)));
  if (badFile) {
    block(`Blocked commit: "${badFile}" must not be committed (data, env, build output or archives). Unstage it and make sure .gitignore covers it.`);
  }

  const diff = [g(['diff', '--cached', '-U0']), commitAll ? g(['diff', '-U0']) : ''].join('\n');
  const secretPatterns = [
    ['Google API key', /AIza[0-9A-Za-z_-]{35}/],
    ['Anthropic API key', /sk-ant-[A-Za-z0-9_-]{20,}/],
    ['API key assignment', /\b(GEMINI_API_KEY|API_KEY|SECRET|TOKEN)\s*[=:]\s*['"]?[A-Za-z0-9_-]{24,}/],
    ['MongoDB URI with credentials', /mongodb(\+srv)?:\/\/[^\s:@/]+:[^\s@/]+@/],
  ];
  for (const line of diff.split('\n')) {
    if (!line.startsWith('+') || line.startsWith('+++')) continue;
    for (const [name, re] of secretPatterns) {
      if (re.test(line)) {
        block(`Blocked commit: possible ${name} in staged changes. Remove it, load it from .env instead, and rotate the key if it was ever pushed. (Value not shown.)`);
      }
    }
  }
}

process.exit(0);
